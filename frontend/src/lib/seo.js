import { pageHead } from "./seoData.js";

const setMeta = (name, content, attr = "name") => {
  let el = document.head.querySelector(`meta[${attr}="${name}"]`);
  if (!el) {
    el = document.createElement("meta");
    el.setAttribute(attr, name);
    document.head.appendChild(el);
  }
  el.setAttribute("content", content);
};

const setCanonical = (href) => {
  let el = document.head.querySelector('link[rel="canonical"]');
  if (!el) {
    el = document.createElement("link");
    el.setAttribute("rel", "canonical");
    document.head.appendChild(el);
  }
  el.setAttribute("href", href);
};

const setAlternates = (alternates) => {
  document.head.querySelectorAll('link[rel="alternate"][hreflang]').forEach((el) => el.remove());
  alternates.forEach(({ hreflang, href }) => {
    const el = document.createElement("link");
    el.setAttribute("rel", "alternate");
    el.setAttribute("hreflang", hreflang);
    el.setAttribute("href", href);
    document.head.appendChild(el);
  });
};

const setJsonLd = (data) => {
  let el = document.getElementById("structured-data");
  if (!el) {
    el = document.createElement("script");
    el.type = "application/ld+json";
    el.id = "structured-data";
    document.head.appendChild(el);
  }
  el.textContent = JSON.stringify(data);
};

// Keeps <head> in sync with the route during client-side navigation.
// The initial HTML of each route is generated by scripts/prerender.mjs from the same data.
export const applyPageSeo = (page) => {
  const head = pageHead(page);
  document.documentElement.lang = head.lang;
  document.title = head.title;
  setMeta("description", head.description);
  setCanonical(head.canonical);
  setAlternates(head.alternates);
  setMeta("og:type", head.ogType, "property");
  setMeta("og:url", head.canonical, "property");
  setMeta("og:title", head.title, "property");
  setMeta("og:description", head.description, "property");
  setMeta("og:locale", head.ogLocale, "property");
  setMeta("og:locale:alternate", head.ogLocaleAlternate, "property");
  setMeta("og:image", head.ogImage, "property");
  setMeta("twitter:title", head.title);
  setMeta("twitter:description", head.description);
  setMeta("twitter:image", head.ogImage);
  setJsonLd(head.jsonLd);
};
